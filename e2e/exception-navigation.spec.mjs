import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1728, height: 966 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const panel = page.locator('.exception-sheet__panel');
const idle = () => page.waitForFunction(() => !document.querySelector('.exception-sheet__panel')?.inert);
let largestHeight = 0;
async function singlePanel() {
  await idle();
  assert.equal(await panel.count(), 1);
  const height = await panel.evaluate(n => n.offsetHeight);
  assert.ok(height >= largestHeight, `Modal shrank from ${largestHeight} to ${height}`);
  largestHeight = height;
  assert.equal(await page.locator('.exception-sheet__backdrop').count(), 1);
  assert.equal(await page.locator('.exception-sheet.is-stacked').count(), 0);
  assert.ok(await panel.evaluate(n => n === window.exceptionPanel));
}
try {
  await page.goto(`${process.env.BASE_URL || 'http://127.0.0.1:5175'}/alarm-rules`);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Alarm rules', exact: true }).click();
  await page.getByRole('button', { name: 'New Alarm Rule', exact: true }).click();
  await page.getByRole('button', { name: /Add exceptions/ }).click();
  await panel.evaluate(n => window.exceptionPanel = n);
  await singlePanel();
  await page.getByRole('button', { name: 'Use shared exception list', exact: true }).click();
  await page.getByRole('heading', { name: 'Shared exception lists', exact: true }).waitFor();
  await singlePanel();
  await panel.getByRole('button', { name: 'Back', exact: true }).click();
  await singlePanel();
  await page.getByRole('button', { name: 'New exception', exact: true }).click();
  await page.getByRole('heading', { name: 'New exception', exact: true }).waitFor();
  await singlePanel();
  assert.ok(await page.getByRole('textbox', {name:'Exception name',exact:true}).evaluate(n => n === document.activeElement));
  await page.screenshot({ path: '/tmp/panasonic-exception-single-sheet.png' });
  await panel.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByRole('heading', { name: 'Exceptions', exact: true }).waitFor();
  await singlePanel();
  assert.equal(await page.locator('.exception-sheet__empty').count(), 1);
  await page.getByRole('button', { name: 'New exception', exact: true }).click();
  await page.getByRole('heading', { name: 'New exception', exact: true }).waitFor();
  await idle();
  await page.getByRole('textbox', { name: 'Exception name', exact: true }).fill('Storm');
  await page.getByRole('button', { name: 'November 20, 2026', exact: true }).click();
  await page.getByRole('button', { name: 'Save Exception', exact: true }).click();
  await page.getByRole('heading', { name: 'Exceptions (1)', exact: true }).waitFor();
  await singlePanel();
  assert.ok(await panel.getByText('Storm', {exact:true}).isVisible());
  await page.getByRole('button', { name: 'Use shared exception list', exact: true }).click();
  await page.getByRole('heading', { name: 'Shared exception lists', exact: true }).waitFor();
  await singlePanel();
  await panel.getByRole('button', { name: 'Back', exact: true }).click();
  await singlePanel();
  await panel.getByRole('button', { name: 'New exception', exact: true }).click();
  await page.getByRole('heading', { name: 'New exception', exact: true }).waitFor();
  await idle();
  await page.reload();
  await page.getByRole('heading', { name: 'New exception', exact: true }).waitFor();
  assert.equal(await panel.count(), 1);
  await page.keyboard.press('Escape');
  await page.getByRole('heading', { name: 'Exceptions (1)', exact: true }).waitFor();
  await idle();
  await panel.getByRole('button', {name:'Save & continue',exact:true}).click();
  await panel.waitFor({state:'detached'});
  assert.ok(await page.locator('.summary-exceptions__row').getByText('Storm',{exact:true}).isVisible());
  assert.deepEqual(errors, []);
  console.log('✓ One panel and backdrop for create/back/save; focus, reload, Escape and Summary return');
} finally { await browser.close(); }
