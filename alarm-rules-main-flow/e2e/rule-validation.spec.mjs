import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base=process.env.BASE_URL || 'http://localhost:5175';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1366,height:900}});
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
const create=()=>page.getByRole('button',{name:'Create Alarm Rule',exact:true});
try {
 await page.goto(`${base}/alarm-rules`);
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('menuitem',{name:'Alarm rules',exact:true}).click();
 await page.getByRole('button',{name:'New Alarm Rule',exact:true}).click();
 assert.ok(await create().isEnabled());
 assert.equal(await page.locator('.alarm-rule__field-error').count(),0);
 await create().click();
 await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Name');
 assert.equal(await page.locator('.alarm-rule__field-error').count(),4);
 assert.equal(Math.round((await page.getByRole('textbox',{name:'Name',exact:true}).boundingBox()).height),52);
 assert.equal(await page.locator('#alarm-error-exceptions').count(),0);
 assert.equal(await page.locator('.rule-guard').count(),0);
 assert.equal(await page.getByRole('textbox',{name:'Name',exact:true}).getAttribute('aria-invalid'),'true');
 await page.screenshot({path:'/tmp/panasonic-rule-inline-errors.png'});
 await page.getByRole('textbox',{name:'Name',exact:true}).fill('Inline validation test');
 assert.equal(await page.locator('#alarm-error-name').count(),0);
 assert.ok(await create().isEnabled());
 await page.getByRole('button',{name:/Add event types/}).click();
 await page.getByRole('button',{name: /^(Add|Edit) Registered people detection$/,exact:true}).click();
 await page.getByRole('button',{name:'Mateo Ruiz',exact:true}).click();
 await page.getByRole('button',{name:/Add [0-9]+ (person|people)/,exact:true}).click();
 await page.getByRole('button',{name:'Save event types',exact:true}).click();
 assert.equal(await page.locator('#alarm-error-events').count(),0);
 await page.getByRole('button',{name:/Add cameras/}).click();
 await page.locator('.camera-sheet__row:not(.is-blocked):not(.is-offline)').first().click();
 await page.locator('.camera-sheet__actions').getByRole('button',{name:'Apply',exact:true}).click();
 await page.locator('.alarm-rule__nav').waitFor();
 await page.locator('.exception-sheet__panel').waitFor({state:'detached'});
 assert.equal(await page.locator('#alarm-error-cameras').count(),0);
 // The screenshot scenario: name, events, cameras filled; schedule missing.
 assert.equal(await page.locator('.alarm-rule__field-error').count(),1);
 await create().click();
 await page.waitForFunction(()=>document.activeElement?.closest('#alarm-section-schedules'));
 assert.ok(await page.locator('#alarm-error-schedules').isVisible());
 assert.ok((await page.locator('#alarm-section-schedules').getAttribute('class')).includes('has-error'));
 await page.screenshot({path:'/tmp/panasonic-rule-missing-schedule.png'});
 await page.getByRole('button',{name:/Add schedule/}).click();
 await page.getByRole('button',{name:'Save time ranges',exact:true}).click();
 await page.getByRole('button',{name:'Save as always on',exact:true}).click();
 await page.getByText('Always on · Alarms appear at all times.',{exact:true}).waitFor();
 assert.equal(await page.locator('#alarm-error-schedules').count(),0);
 assert.equal(await page.locator('.alarm-rule__field-error').count(),0);
 await create().click();
 await page.getByRole('dialog',{name:'Alarm rules',exact:true}).waitFor();
 assert.ok(await page.getByRole('switch',{name:'Inline validation test',exact:true}).isVisible());
 assert.deepEqual(errors,[]);
 console.log('✓ Always-active button, field errors, first-error focus, live error clearing, optional exceptions, explicit always-on and successful creation');
} finally {await browser.close();}
